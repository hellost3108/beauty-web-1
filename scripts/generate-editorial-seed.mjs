import { writeFileSync } from "node:fs";
import { blogPosts } from "../src/data/melalogyBlogPosts.ts";
import { magazineEditorialPosts } from "../src/data/melalogyMagazinePosts.ts";
import { defaultAboutContent } from "../src/data/aboutContent.ts";

const outputPath = new URL("../supabase/seed_editorial.sql", import.meta.url);
const rows = [
  ...blogPosts.map((post) => ({
    channel: "blog",
    slug: String(post.id),
    title: post.title,
    seoTitle: post.seoTitle,
    metaDescription: post.metaDescription,
    keywords: post.keywords,
    subtitle: null,
    excerpt: post.excerpt,
    author: post.author,
    authorRole: null,
    dateLabel: post.date,
    publishedAt: post.publishedAt,
    category: post.category,
    imageUrl: post.image,
    imageAlt: post.imageAlt,
    readingTime: post.readingTime,
    contentHtml: post.content.trim(),
    featured: post.id === 1,
    sortOrder: post.id * 10,
  })),
  ...magazineEditorialPosts.map((post) => ({
    channel: "magazine",
    slug: String(post.id),
    title: post.title,
    seoTitle: post.seoTitle,
    metaDescription: post.metaDescription,
    keywords: post.keywords,
    subtitle: post.subtitle,
    excerpt: post.excerpt,
    author: post.author,
    authorRole: post.role,
    dateLabel: post.date,
    publishedAt: post.publishedAt,
    category: post.category,
    imageUrl: post.image,
    imageAlt: post.imageAlt,
    readingTime: post.readTime,
    contentHtml: post.content.trim(),
    featured: post.id === 1,
    sortOrder: post.id * 10,
  })),
];

const seedRows = rows.map((row) => ({
  channel: row.channel,
  slug: row.slug,
  title: row.title,
  seo_title: row.seoTitle,
  meta_description: row.metaDescription,
  keywords: row.keywords,
  subtitle: row.subtitle,
  excerpt: row.excerpt,
  author: row.author,
  author_role: row.authorRole,
  date_label: row.dateLabel,
  published_at: row.publishedAt,
  category: row.category,
  image_url: row.imageUrl,
  image_alt: row.imageAlt,
  reading_time: row.readingTime,
  content_html: row.contentHtml,
  status: "published",
  featured: row.featured,
  sort_order: row.sortOrder,
}));

const articleSql = `
insert into public.articles (
  channel, slug, title, seo_title, meta_description, keywords, subtitle, excerpt,
  author, author_role, date_label, published_at, category, image_url, image_alt,
  reading_time, content_html, status, featured, sort_order
)
select
  seed.channel::public.content_channel,
  seed.slug,
  seed.title,
  seed.seo_title,
  seed.meta_description,
  seed.keywords,
  seed.subtitle,
  seed.excerpt,
  seed.author,
  seed.author_role,
  seed.date_label,
  seed.published_at,
  seed.category,
  seed.image_url,
  seed.image_alt,
  seed.reading_time,
  seed.content_html,
  seed.status::public.publication_status,
  seed.featured,
  seed.sort_order
from jsonb_to_recordset(
  $editorial_articles$${JSON.stringify(seedRows)}$editorial_articles$::jsonb
) as seed (
  channel text,
  slug text,
  title text,
  seo_title text,
  meta_description text,
  keywords text[],
  subtitle text,
  excerpt text,
  author text,
  author_role text,
  date_label text,
  published_at timestamptz,
  category text,
  image_url text,
  image_alt text,
  reading_time text,
  content_html text,
  status text,
  featured boolean,
  sort_order integer
)
on conflict (channel, slug) do update set
  title = excluded.title,
  seo_title = excluded.seo_title,
  meta_description = excluded.meta_description,
  keywords = excluded.keywords,
  subtitle = excluded.subtitle,
  excerpt = excluded.excerpt,
  author = excluded.author,
  author_role = excluded.author_role,
  date_label = excluded.date_label,
  published_at = excluded.published_at,
  category = excluded.category,
  image_url = excluded.image_url,
  image_alt = excluded.image_alt,
  reading_time = excluded.reading_time,
  content_html = excluded.content_html,
  status = excluded.status,
  featured = excluded.featured,
  sort_order = excluded.sort_order;
`;

const aboutSql = `
insert into public.content_pages (
  slug, title, seo_title, seo_description, content, status
) values (
  'about',
  'Giới thiệu Melalogy',
  'Giới Thiệu Melalogy | Hiểu Làn Da, Chọn Đúng Điều Cần',
  'Khám phá câu chuyện, triết lý và những giá trị Melalogy theo đuổi trong hành trình chăm sóc làn da Việt.',
  $about_content$${JSON.stringify(defaultAboutContent)}$about_content$::jsonb,
  'published'
)
on conflict (slug) do update set
  title = excluded.title,
  seo_title = excluded.seo_title,
  seo_description = excluded.seo_description,
  content = excluded.content,
  status = excluded.status;
`;

writeFileSync(
  outputPath,
  `-- Generated by scripts/generate-editorial-seed.mjs.\n-- Safe to run repeatedly.\n${articleSql}\n${aboutSql}`,
);
