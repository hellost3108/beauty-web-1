create extension if not exists pgcrypto;

create type public.user_role as enum (
  'customer',
  'editor',
  'admin',
  'super_admin'
);

create type public.publication_status as enum (
  'draft',
  'published',
  'archived'
);

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null default '',
  full_name text,
  role public.user_role not null default 'customer',
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.categories (
  id bigint generated by default as identity primary key,
  parent_id bigint references public.categories(id) on delete set null,
  name text not null,
  slug text not null unique,
  description text,
  image_url text,
  is_active boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint categories_name_not_blank check (length(trim(name)) > 0),
  constraint categories_slug_format check (slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$')
);

create table public.products (
  id bigint generated by default as identity primary key,
  category_id bigint references public.categories(id) on delete set null,
  name text not null,
  slug text not null unique,
  sku text unique,
  subtitle text,
  short_description text,
  description text,
  ingredients text,
  usage text,
  price integer not null default 0,
  compare_at_price integer,
  status public.publication_status not null default 'draft',
  featured boolean not null default false,
  sort_order integer not null default 0,
  seo_title text,
  seo_description text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint products_name_not_blank check (length(trim(name)) > 0),
  constraint products_slug_format check (slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'),
  constraint products_price_non_negative check (price >= 0),
  constraint products_compare_at_price_non_negative check (compare_at_price is null or compare_at_price >= 0)
);

create table public.product_images (
  id uuid primary key default gen_random_uuid(),
  product_id bigint not null references public.products(id) on delete cascade,
  storage_path text,
  image_url text not null,
  alt_text text,
  sort_order integer not null default 0,
  is_primary boolean not null default false,
  created_at timestamptz not null default now(),
  constraint product_images_url_not_blank check (length(trim(image_url)) > 0)
);

create unique index product_images_one_primary_per_product
  on public.product_images(product_id)
  where is_primary;

create index product_images_product_sort_idx
  on public.product_images(product_id, sort_order);

create table public.banners (
  id bigint generated by default as identity primary key,
  name text not null,
  placement text not null default 'home_hero',
  eyebrow text,
  title text not null,
  highlighted_text text,
  subtitle text,
  desktop_image_url text not null,
  mobile_image_url text,
  button_label text,
  button_url text,
  secondary_button_label text,
  secondary_button_url text,
  sort_order integer not null default 0,
  status public.publication_status not null default 'draft',
  starts_at timestamptz,
  ends_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint banners_name_not_blank check (length(trim(name)) > 0),
  constraint banners_title_not_blank check (length(trim(title)) > 0),
  constraint banners_dates_valid check (ends_at is null or starts_at is null or ends_at > starts_at)
);

create index banners_public_listing_idx
  on public.banners(placement, status, sort_order);

create table public.homepage_sections (
  id bigint generated by default as identity primary key,
  section_key text not null unique,
  eyebrow text,
  title text not null,
  highlighted_text text,
  subtitle text,
  body text,
  image_url text,
  cta_label text,
  cta_url text,
  content jsonb not null default '{}'::jsonb,
  sort_order integer not null default 0,
  status public.publication_status not null default 'draft',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint homepage_sections_key_format check (section_key ~ '^[a-z0-9]+(?:_[a-z0-9]+)*$'),
  constraint homepage_sections_title_not_blank check (length(trim(title)) > 0)
);

create table public.site_settings (
  key text primary key,
  value jsonb not null default 'null'::jsonb,
  is_public boolean not null default false,
  updated_at timestamptz not null default now(),
  constraint site_settings_key_format check (key ~ '^[a-z0-9]+(?:_[a-z0-9]+)*$')
);

